// Return localized news items
export function getLocalizedNewsItems(language: string): MarineNewsItem[] {
  const langKey = NEWS_TRANSLATIONS[language] ? language : 'en';
  if (langKey === 'en') {
    return MARINE_NEWS_DB;
  }

  const translations = NEWS_TRANSLATIONS[langKey] || {};

  return MARINE_NEWS_DB.map((item) => {
    const tr = translations[item.id];
    if (!tr) return item;
    return {
      ...item,
      title: tr.title || item.title,
      summary: tr.summary || item.summary,
      content: tr.content || item.content,
      keyTakeaway: tr.keyTakeaway || item.keyTakeaway
    };
  });
}

